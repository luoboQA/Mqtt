import os
import signal
import socket
import struct
import subprocess
import time
import unittest

import sol_test

CONF_PATH = '/tmp/sol_limits_test.conf'
LOG_PATH = '/tmp/sol_limits_test.log'
HOST, PORT = '127.0.0.1', 18885

CONF = """# Generated by tests/integration/test_limits.py
log_level WARNING
log_path {log}
max_request_size 64KB
keepalive 60s
retransmit_interval 2s
{extra}
"""


class TestLimits(unittest.TestCase):
    """The per session and per address quotas: publish rate, inflight window
    and simultaneous connections. Each case starts a broker of its own,
    because the limits are configuration and would interfere with each
    other"""

    def setUp(self):
        self.broker = None

    def tearDown(self):
        self.stop_broker()

    # -- harness ------------------------------------------------------

    def start_broker(self, extra=''):
        with open(CONF_PATH, 'w') as fh:
            fh.write(CONF.format(log=LOG_PATH, extra=extra))
        self.broker = subprocess.Popen(
            f'{sol_test.broker_bin()} -a {HOST} -p {PORT} '
            f'-c {CONF_PATH}'.split(),
            stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT,
            preexec_fn=os.setsid)
        deadline = time.time() + 5
        while time.time() < deadline:
            try:
                socket.create_connection((HOST, PORT), timeout=0.5).close()
                # The readiness probe counts against max_connections_per_ip
                # until the broker notices it is gone
                time.sleep(0.2)
                return
            except OSError:
                time.sleep(0.05)
        self.fail('the broker did not come up')

    def stop_broker(self):
        if not self.broker:
            return
        os.kill(self.broker.pid, signal.SIGTERM)
        self.broker.wait(timeout=5)
        self.broker = None

    def connect(self, client_id, clean_session=True):
        conn = socket.create_connection((HOST, PORT), timeout=5)
        conn.settimeout(5)
        conn.sendall(sol_test.create_connect(client_id,
                                             clean_session=clean_session))
        buf = b''
        while len(buf) < 4:
            chunk = conn.recv(100)
            self.assertTrue(chunk, 'the broker refused the connection')
            buf += chunk
        connack, rc = sol_test.read_connack(buf[:4])
        self.assertEqual((connack, rc), (32, 0))
        return conn, buf[4:]

    def subscribe(self, conn, mid, topics, buf=b''):
        conn.sendall(sol_test.create_subscribe(mid, topics))
        while len(buf) < 2 or len(buf) < 2 + buf[1]:
            buf += conn.recv(2048)
        header, ack_mid, granted = sol_test.read_suback(buf[:2 + buf[1]])
        self.assertEqual(header, 0x90)
        self.assertEqual(ack_mid, mid)
        return granted, buf[2 + buf[1]:]

    @staticmethod
    def recv_packet(conn, buf=b''):
        """Next full MQTT packet of the stream and what is left after it"""
        while len(buf) < 2:
            chunk = conn.recv(4096)
            if not chunk:
                return None, b''
            buf += chunk
        mult, remaining, pos = 1, 0, 1
        while True:
            while len(buf) <= pos:
                chunk = conn.recv(4096)
                if not chunk:
                    return None, b''
                buf += chunk
            byte = buf[pos]
            remaining += (byte & 127) * mult
            mult *= 128
            pos += 1
            if not byte & 128:
                break
        total = pos + remaining
        while len(buf) < total:
            chunk = conn.recv(4096)
            if not chunk:
                return None, b''
            buf += chunk
        return buf[:total], buf[total:]

    def publish(self, conn, topic, payload, qos=1, mid=1):
        conn.sendall(sol_test.create_publish(topic, payload, qos=qos, mid=mid))

    # -- tests --------------------------------------------------------

    def test_publish_rate_limit_acks_but_drops(self):
        """Over max_publish_rate the extra packets are dropped, but the QoS 1
        acknowledgement still flows: leaving them unacknowledged would only
        make the client retransmit them forever"""
        self.start_broker('max_publish_rate 5\n')

        sub, buf = self.connect('rate-sub')
        self.subscribe(sub, 1, {'rate/topic': 1}, buf)
        pub, _ = self.connect('rate-pub')
        try:
            for mid in range(1, 41):
                self.publish(pub, 'rate/topic', b'x', mid=mid)
            # Every publish is acknowledged, even the dropped ones
            acks = set()
            pub.settimeout(5)
            buf = b''
            deadline = time.time() + 5
            while len(acks) < 40 and time.time() < deadline:
                packet, buf = self.recv_packet(pub, buf)
                if packet is None:
                    break
                if packet[0] & 0xF0 == 0x40:  # PUBACK
                    acks.add(struct.unpack('!H', packet[2:4])[0])
            self.assertEqual(len(acks), 40,
                             'a rate limited publish was not acknowledged')

            # The subscriber sees only what passed the bucket
            delivered = set()
            sub.settimeout(1.5)
            buf = b''
            deadline = time.time() + 1.5
            while time.time() < deadline:
                try:
                    packet, buf = self.recv_packet(sub, buf)
                except socket.timeout:
                    break
                if packet is None:
                    break
                _, _, _, mid = sol_test.read_publish(packet)
                if mid is not None:
                    delivered.add(mid)
                    sub.sendall(sol_test.create_puback(mid))
            self.assertGreater(len(delivered), 0,
                               'the rate limit dropped everything')
            self.assertLess(len(delivered), 40,
                            'the rate limit did not drop anything')
        finally:
            sub.close()
            pub.close()

    def test_inflight_window_bounds_the_offline_queue(self):
        """A session away from its client accepts at most max_inflight
        messages: the rest is dropped instead of growing the queue without
        bound, and the client gets exactly the window on reconnect"""
        self.start_broker('max_inflight 5\n')

        sub, buf = self.connect('win-sub', clean_session=False)
        self.subscribe(sub, 1, {'win/topic': 1}, buf)
        sub.close()
        time.sleep(0.2)

        pub, _ = self.connect('win-pub')
        try:
            for mid in range(1, 13):
                self.publish(pub, 'win/topic', b'x' * 16, mid=mid)
                # Each inbound publish is acknowledged independently of the
                # subscriber window
                pub.recv(100)
        finally:
            pub.close()

        again, buf = self.connect('win-sub', clean_session=False)
        delivered = set()
        try:
            again.settimeout(1.5)
            deadline = time.time() + 1.5
            while time.time() < deadline:
                try:
                    packet, buf = self.recv_packet(again, buf)
                except socket.timeout:
                    break
                if packet is None:
                    break
                _, _, _, mid = sol_test.read_publish(packet)
                if mid is not None:
                    delivered.add(mid)
                    again.sendall(sol_test.create_puback(mid))
        finally:
            again.close()

        self.assertEqual(len(delivered), 5,
                         'the inflight window did not bound the queue: %d '
                         'messages queued' % len(delivered))

    def test_max_connections_per_ip(self):
        """The third connection from one address is closed right after
        accept, and the slot comes back when one of the first two goes
        away"""
        self.start_broker('max_connections_per_ip 2\n')

        first, _ = self.connect('ip-1')
        second, _ = self.connect('ip-2')
        try:
            third = socket.create_connection((HOST, PORT), timeout=5)
            third.settimeout(3)
            try:
                third.sendall(sol_test.create_connect('ip-3'))
                answer = b''
                try:
                    answer = third.recv(100)
                except (ConnectionResetError, socket.timeout):
                    pass
                self.assertNotEqual(answer[:1], b'\x20',
                                    'the broker accepted a connection over '
                                    'max_connections_per_ip')
            finally:
                third.close()

            # A slot is free again once one of the live clients disconnects
            first.close()
            first = None
            time.sleep(0.3)
            again, _ = self.connect('ip-4')
            again.close()
        finally:
            if first:
                first.close()
            second.close()

    def test_invalid_utf8_publish_disconnects(self):
        """A topic name that is not well formed UTF-8 is a protocol error:
        the broker closes the connection instead of storing a key it cannot
        compare (§1.5.3, §3.3.2)"""
        self.start_broker()
        conn, _ = self.connect('utf8-pub')
        try:
            # Topic 0xC3 0x28, not a valid UTF-8 sequence
            conn.sendall(bytes([0x30, 0x06, 0x00, 0x02, 0xC3, 0x28]) + b'hi')
            conn.settimeout(3)
            answer = b''
            try:
                answer = conn.recv(100)
            except (ConnectionResetError, socket.timeout):
                pass
            self.assertEqual(answer, b'',
                             'the broker kept the connection after an invalid '
                             'UTF-8 topic')
        finally:
            conn.close()

    def test_invalid_utf8_client_id_disconnects(self):
        """Same for the client id: the CONNECT is malformed, no CONNACK"""
        self.start_broker()
        conn = socket.create_connection((HOST, PORT), timeout=5)
        conn.settimeout(3)
        try:
            # client id 0xC0 0xAF, an overlong encoding of '/'
            conn.sendall(bytes([0x10, 0x0E, 0x00, 0x04]) + b'MQTT' +
                         bytes([0x04, 0x02, 0x00, 0x3C, 0x00, 0x02,
                                0xC0, 0xAF]))
            answer = b''
            try:
                answer = conn.recv(100)
            except (ConnectionResetError, socket.timeout):
                pass
            self.assertEqual(answer, b'',
                             'the broker answered a CONNECT with an invalid '
                             'UTF-8 client id')
        finally:
            conn.close()

    def test_invalid_utf8_subscription_gets_failure_code(self):
        """A malformed filter only fails its own SUBACK slot, the rest of the
        packet and the connection are untouched"""
        self.start_broker()
        conn, _ = self.connect('utf8-sub')
        try:
            # One filter, 0xC3 0x28, which is not valid UTF-8
            conn.sendall(bytes([0x82, 0x07, 0x00, 0x01, 0x00, 0x02,
                                0xC3, 0x28, 0x01]))
            conn.settimeout(3)
            packet, _ = self.recv_packet(conn)
            self.assertIsNotNone(packet, 'the broker closed the connection')
            header, mid, granted = sol_test.read_suback(packet)
            self.assertEqual(header, 0x90)
            self.assertEqual(mid, 1)
            self.assertEqual(granted, 0x80,
                             'a malformed filter was granted')

            # The connection is still usable
            conn.sendall(bytes([0xC0, 0x00]))  # PINGREQ
            packet, _ = self.recv_packet(conn)
            self.assertEqual(packet[0], 0xD0)
        finally:
            conn.close()


if __name__ == '__main__':
    unittest.main()
