import os
import signal
import socket
import subprocess
import time
import unittest
import sol_test

CONF_PATH = '/tmp/sol_memory_test.conf'
LOG_PATH = '/tmp/sol_memory_test.log'
HOST, PORT = '127.0.0.1', 18886

CONF = """# Generated by tests/integration/test_memory.py
log_level WARNING
log_path {log}
reclaim_interval 1s
stats_publish_interval 1s
# Small buffers: every connection allocates two of them, and this test
# measures memory down to the kilobyte
max_request_size 64KB
keepalive 60s
retransmit_interval 2s
{extra}
"""


class TestMemory(unittest.TestCase):
    """The max_memory policy, in the order the configuration promises: the
    topics nothing refers to anymore are reclaimed, then the oldest messages
    queued for the clients that are away are dropped, and when even that is
    not enough the broker stops accepting connections until it recovers"""

    def setUp(self):
        self.broker = None
        self.watcher = None

    def tearDown(self):
        if self.watcher:
            self.watcher.close()
            self.watcher = None
        self.stop_broker()

    # -- harness ------------------------------------------------------

    def write_conf(self, extra=''):
        with open(CONF_PATH, 'w') as fh:
            fh.write(CONF.format(log=LOG_PATH, extra=extra))

    def start_broker(self):
        self.broker = subprocess.Popen(
            f'./sol -a {HOST} -p {PORT} -c {CONF_PATH}'.split(),
            stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT,
            preexec_fn=os.setsid)
        deadline = time.time() + 5
        while time.time() < deadline:
            try:
                socket.create_connection((HOST, PORT), timeout=0.5).close()
                return
            except OSError:
                time.sleep(0.05)
        self.fail('the broker did not come up')

    def stop_broker(self):
        if not self.broker:
            return
        os.kill(self.broker.pid, signal.SIGTERM)
        self.broker.wait(timeout=5)
        self.broker = None

    def connect(self, client_id, clean_session=True):
        conn = socket.create_connection((HOST, PORT), timeout=5)
        conn.settimeout(5)
        conn.sendall(sol_test.create_connect(client_id,
                                             clean_session=clean_session))
        buf = b''
        while len(buf) < 4:
            chunk = conn.recv(100)
            self.assertTrue(chunk, 'the broker refused the connection')
            buf += chunk
        return conn, buf

    def subscribe(self, conn, mid, topics):
        conn.sendall(sol_test.create_subscribe(mid, topics))
        conn.settimeout(3)
        buf = b''
        while len(buf) < 2 or len(buf) < 2 + buf[1]:
            buf += conn.recv(2048)
        code, ack_mid, _ = sol_test.read_suback(buf[:2 + buf[1]])
        self.assertEqual(code, 0x90)
        return buf[2 + buf[1]:]

    def connect_resumed(self, client_id):
        """Reconnect a persistent session, returning the bytes the broker
        packed behind the CONNACK: the queued messages share its write buffer
        and can land in the very same TCP segment"""
        conn = socket.create_connection((HOST, PORT), timeout=5)
        conn.settimeout(5)
        conn.sendall(sol_test.create_connect(client_id, clean_session=False))
        buf = b''
        while len(buf) < 4:
            chunk = conn.recv(4096)
            self.assertTrue(chunk, 'the broker closed on reconnect')
            buf += chunk
        return conn, buf[4:]

    def watcher_connection(self):
        """One long lived connection subscribed to the memory statistic: a
        fresh client per read would allocate a megabyte of buffers of its own
        and pollute the very number being measured"""
        conn, _ = self.connect('mem-watch')
        self.subscribe(conn, 1, {'$SOL/broker/memory/used/': 0})
        self.watcher = conn
        return conn

    def memory_used(self):
        """Next $SOL/broker/memory/used/ payload published after the call"""
        if not self.watcher:
            self.watcher_connection()
        self.watcher.settimeout(8)
        buf = b''
        while True:
            while buf:
                body, remaining = sol_test.mqtt_decode_len(buf)
                total = (len(buf) - len(body)) + remaining
                if len(buf) < total:
                    break
                _, topic, payload, _ = sol_test.read_publish(buf[:total])
                buf = buf[total:]
                if topic == '$SOL/broker/memory/used/':
                    return int(payload)
            chunk = self.watcher.recv(4096)
            if not chunk:
                # The tests restart the broker: the watcher connection dies
                # with it, so open a fresh one and start reading again
                self.watcher.close()
                self.watcher = None
                self.watcher_connection()
                buf = b''
                continue
            buf += chunk

    # -- tests --------------------------------------------------------

    def test_unused_topics_are_reclaimed(self):
        """Every topic ever published to stays in the store forever: the
        periodic reclamation releases the ones nothing refers to anymore (no
        subscriber, no retained message), and the memory comes back down"""
        self.write_conf()
        self.start_broker()

        # A wildcard subscription pins every topic published under it, so the
        # flood below cannot be reclaimed before it is measured. The clients
        # are all connected before the baseline is read: a new connection
        # allocates its own read and write buffers, which would show up in
        # the measurement as if the store had grown
        sub, _ = self.connect('mem-sub')
        pub, _ = self.connect('mem-pub')
        try:
            self.subscribe(sub, 1, {'gc/#': 0})
            self.memory_used()  # make sure the watcher connection exists
            time.sleep(1.2)     # let a statistics tick pass

            before = self.memory_used()

            # 300 topics: each one costs a topic struct, its name and the
            # trie nodes of the key
            try:
                for i in range(300):
                    pub.sendall(sol_test.create_publish(
                        b'gc/topic/%d' % i, b'x', qos=0))
            finally:
                pass
            time.sleep(1.2)
            grown = self.memory_used()
            self.assertGreater(grown, before, 'the flood did not grow the store')

            # Nothing holds them anymore: the reclamation (every second in
            # this configuration) has to give the memory back
            sub.sendall(sol_test.create_unsubscribe(2, 'gc/#'))
            sub.recv(100)  # UNSUBACK
        finally:
            pub.close()
            sub.close()

        time.sleep(3)
        after = self.memory_used()
        self.assertLess(after, grown, 'the unused topics were never released')
        self.assertLess(after - before, 8192,
                        'the store did not come back to its baseline')

    def test_memory_pressure_drops_the_oldest_queued_messages(self):
        """Over the limit and with nothing reclaimable left, the broker gives
        back the oldest messages queued for the clients that are away: a
        persistent session reconnecting gets a trimmed backlog instead of the
        broker refusing to work"""
        # The limit is computed from what this very broker holds, so the test
        # does not depend on the machine: a first run measures, the second one
        # lives 128KB above that baseline
        self.write_conf()
        self.start_broker()
        baseline = self.memory_used()
        self.stop_broker()

        self.write_conf('max_memory %d' % (baseline + 128 * 1024))
        self.start_broker()

        sub, _ = self.connect('memq-sub', clean_session=False)
        self.subscribe(sub, 1, {'memq/topic': 1})
        sub.close()
        time.sleep(0.3)

        # 400 messages of 1KB for a client that is away: they pile up in the
        # session queue, well past the headroom the limit allows
        pub, _ = self.connect('memq-pub')
        payload = b'q' * 1024
        try:
            for mid in range(1, 401):
                pub.sendall(sol_test.create_publish('memq/topic', payload,
                                                    qos=1, mid=mid % 65535 + 1))
                pub.recv(100)  # PUBACK
        finally:
            pub.close()
        # The policy trims the queue on its periodic check, and while it is
        # still over the limit new connections are refused: wait for the
        # memory to come back down before reconnecting (the watcher
        # connection predates the pressure, so reading the statistic does not
        # need a new one). Slower machines, a sanitizer build for instance,
        # take a few checks to get there
        deadline = time.time() + 20
        while True:
            try:
                again, buf = self.connect_resumed('memq-sub')
                break
            except (ConnectionResetError, OSError):
                # The broker is still refusing: the flag it raises under
                # memory pressure is cleared on the periodic check that finds
                # the broker back under its limit, one tick after the trim
                if time.time() > deadline:
                    raise
                time.sleep(0.5)
        try:
            again.settimeout(2)
            # Identifiers, not deliveries: the retransmission scan sends the
            # same message again until it is acknowledged, and counting those
            # would hide what the policy dropped
            delivered = set()
            try:
                while True:
                    buf += again.recv(65536)
                    while buf:
                        body, remaining = sol_test.mqtt_decode_len(buf)
                        total = (len(buf) - len(body)) + remaining
                        if len(buf) < total:
                            break
                        _, _, _, mid = sol_test.read_publish(buf[:total])
                        buf = buf[total:]
                        if mid is not None:
                            delivered.add(mid)
                            again.sendall(sol_test.create_puback(mid))
            except socket.timeout:
                pass
            self.assertGreater(len(delivered), 0, 'the whole backlog was dropped')
            self.assertLess(len(delivered), 400,
                            'nothing was dropped under memory pressure')
        finally:
            again.close()

        # The broker is still there, accepting connections: the policy does
        # not leave it in a state where nothing can connect anymore. Note the
        # absolute memory is not asserted here, every connection this test
        # opens adds its own buffers to the number
        conn, _ = self.connect('memq-alive')
        conn.close()

        conn, _ = self.connect('memq-alive')
        conn.close()

    def test_over_the_limit_refuses_new_connections(self):
        """A limit the broker cannot honour even after reclaiming everything
        (here: below the memory the process starts with) makes it refuse new
        connections, and say so once, instead of pretending to work"""
        self.write_conf('max_memory 1MB')
        self.start_broker()
        time.sleep(1.5)  # let a memory check run and set the flag

        refused = 0
        for _ in range(3):
            conn = socket.create_connection((HOST, PORT), timeout=5)
            conn.settimeout(2)
            try:
                conn.sendall(sol_test.create_connect('over-limit'))
                self.assertEqual(conn.recv(100), b'',
                                 'a connection was accepted over the limit')
                refused += 1
            except (ConnectionResetError, BrokenPipeError):
                refused += 1
            finally:
                conn.close()
        self.assertEqual(refused, 3)

        with open(LOG_PATH, 'rb') as fh:
            log = fh.read()
        self.assertIn(b'refusing new connections', log)
        self.assertIn(b'below the memory the broker already uses', log)


if __name__ == '__main__':
    unittest.main()
