import os
import signal
import socket
import subprocess
import time
import unittest
import sol_test

CONF_PATH = '/tmp/sol_daemon_test.conf'
LOG_PATH = '/tmp/sol_daemon_test.log'
HOST, PORT = '127.0.0.1', 18890

CONF = """# Generated by tests/integration/test_daemon.py
# A daemonized broker redirects its standard streams to /dev/null, so its log
# file is the only place anything can be observed: the level has to be quiet
# enough to start and loud enough to show the two anchor lines used below
log_level INFORMATION
log_path {log}
keepalive 60s
"""


def broker_pid_by_port(port):
    """The pid listening on `port`, or None. The daemonized broker has no
    pid file and the process the shell gets is the parent, which exits
    immediately, so the listening socket is what identifies it"""
    try:
        out = subprocess.run(['ss', '-ltnp'], capture_output=True,
                             text=True, timeout=5).stdout
    except (OSError, subprocess.TimeoutExpired):
        return None
    for line in out.splitlines():
        if ':%d ' % port in line and 'pid=' in line:
            return int(line.split('pid=')[1].split(',')[0])
    return None


def wait_for_log(pattern, timeout=5):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with open(LOG_PATH, 'rb') as fh:
                if pattern in fh.read():
                    return True
        except FileNotFoundError:
            pass
        time.sleep(0.1)
    return False


class TestDaemon(unittest.TestCase):
    """Daemon mode: the broker forks itself into the background, everything it
    prints is gone (standard streams point at /dev/null) and it stays
    reachable and stoppable, which is what makes it usable from a service
    manager"""

    def setUp(self):
        self.pid = None
        if os.path.exists(LOG_PATH):
            os.remove(LOG_PATH)
        with open(CONF_PATH, 'w') as fh:
            fh.write(CONF.format(log=LOG_PATH))

    def tearDown(self):
        if self.pid:
            try:
                os.kill(self.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
            deadline = time.time() + 5
            while time.time() < deadline and self.pid_alive():
                time.sleep(0.05)

    def pid_alive(self):
        try:
            os.kill(self.pid, 0)
            return True
        except ProcessLookupError:
            return False

    def start_daemon(self):
        """Start the broker with -d and return once it is listening"""
        started = subprocess.run(
            f'./sol -d -a {HOST} -p {PORT} -c {CONF_PATH}'.split(),
            timeout=5)
        self.assertEqual(started.returncode, 0,
                         'the parent should return immediately')

        deadline = time.time() + 5
        while time.time() < deadline:
            self.pid = broker_pid_by_port(PORT)
            if self.pid:
                try:
                    socket.create_connection((HOST, PORT), timeout=0.5).close()
                    return
                except OSError:
                    pass
            time.sleep(0.05)
        self.fail('the daemonized broker never listened')

    def test_daemon_runs_detached_and_stops_on_sigterm(self):
        self.start_daemon()

        # A client can connect and finish a handshake, as usual
        conn = socket.create_connection((HOST, PORT), timeout=5)
        conn.settimeout(3)
        try:
            conn.sendall(sol_test.create_connect('daemon-check'))
            connack, rc = sol_test.read_connack(conn.recv(100))
            self.assertEqual(connack, 32)
            self.assertEqual(rc, 0)
        finally:
            conn.close()

        self.assertTrue(wait_for_log(b'Server start'),
                        'nothing was written to the configured log file')

        # SIGTERM stops it, and the shutdown is logged (the file is the only
        # place this can be seen, the streams are gone)
        os.kill(self.pid, signal.SIGTERM)
        deadline = time.time() + 5
        while time.time() < deadline and self.pid_alive():
            time.sleep(0.05)
        self.assertFalse(self.pid_alive(), 'the daemon did not stop')
        self.assertTrue(wait_for_log(b'exiting'),
                        'the clean shutdown was not logged')
        self.pid = None


if __name__ == '__main__':
    unittest.main()
