import os
import signal
import socket
import subprocess
import time
import unittest
import sol_test

CONF_PATH = '/tmp/sol_acl_test.conf'
ACL_PATH = '/tmp/sol_acl_test.acl'
LOG_PATH = '/tmp/sol_acl_test.log'
HOST, PORT = '127.0.0.1', 18887

ACL = """# Access control list used by tests/integration/test_acl.py
# sensor-1 owns its tree, alice may only read it, anybody may use public/#
allow readwrite client:sensor-1   sensors/#
allow readwrite client:sensor-2   sensors/#
allow read        user:alice      sensors/#
allow readwrite *                 public/#
"""

CONF = """# Generated by tests/integration/test_acl.py
log_level WARNING
log_path {log}
acl_file {acl}
max_request_size 64KB
keepalive 60s
"""


class TestAcl(unittest.TestCase):
    """Topic level authorization: authentication says who a client is, the
    access control list says what it may read and write. Rules are evaluated
    in order and a topic no rule covers is denied"""

    def setUp(self):
        self.broker = None
        with open(ACL_PATH, 'w') as fh:
            fh.write(ACL)
        with open(CONF_PATH, 'w') as fh:
            fh.write(CONF.format(log=LOG_PATH, acl=ACL_PATH))
        self.start_broker()

    def tearDown(self):
        self.stop_broker()

    # -- harness ------------------------------------------------------

    def start_broker(self):
        self.broker = subprocess.Popen(
            f'{sol_test.broker_bin()} -a {HOST} -p {PORT} '
            f'-c {CONF_PATH}'.split(),
            stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT,
            preexec_fn=os.setsid)
        deadline = time.time() + 5
        while time.time() < deadline:
            try:
                socket.create_connection((HOST, PORT), timeout=0.5).close()
                return
            except OSError:
                time.sleep(0.05)
        self.fail('the broker did not come up')

    def stop_broker(self):
        if not self.broker:
            return
        os.kill(self.broker.pid, signal.SIGTERM)
        self.broker.wait(timeout=5)
        self.broker = None

    def connect(self, client_id, username=None, **kwargs):
        """Connect and return (conn, connack_bytes, leftover)"""
        conn = socket.create_connection((HOST, PORT), timeout=5)
        conn.settimeout(3)
        conn.sendall(sol_test.create_connect(client_id, username=username,
                                             **kwargs))
        buf = b''
        while len(buf) < 4:
            chunk = conn.recv(100)
            self.assertTrue(chunk, 'the broker closed without a CONNACK')
            buf += chunk
        return conn, buf[:4], buf[4:]

    def subscribed(self, conn, mid, topic):
        """Subscribe and return the granted code of the first entry"""
        conn.sendall(sol_test.create_subscribe(mid, {topic: 0}))
        packet = conn.recv(100)
        code, ack_mid, granted = sol_test.read_suback(packet)
        self.assertEqual(code, 0x90)
        return granted

    def assert_nothing_arrives(self, conn, timeout=1.0):
        conn.settimeout(timeout)
        try:
            self.assertEqual(conn.recv(2048), b'')
        except socket.timeout:
            pass

    # -- tests --------------------------------------------------------

    def test_allowed_client_can_use_its_tree(self):
        """A rule naming the client id allows reading and writing under the
        filter the rule spells"""
        sub, _, _ = self.connect('sensor-1')
        try:
            self.assertEqual(self.subscribed(sub, 1, 'sensors/temperature'), 0)

            pub, _, _ = self.connect('sensor-2')
            try:
                pub.sendall(sol_test.create_publish('sensors/temperature',
                                                    b'21.5', qos=1, mid=7))
                self.assertEqual(sol_test.read_ack(pub.recv(100))[0], 0x40)
                _, topic, payload, _ = sol_test.read_publish(sub.recv(100))
                self.assertEqual(topic, 'sensors/temperature')
                self.assertEqual(payload, b'21.5')
            finally:
                pub.close()
        finally:
            sub.close()

    def test_denied_subscription_is_answered_with_failure_code(self):
        """A filter no rule allows is refused with the 0x80 code of §3.8.4,
        the rest of the session stays usable"""
        conn, _, _ = self.connect('guest')
        try:
            self.assertEqual(self.subscribed(conn, 1, 'sensors/temperature'),
                             0x80)
            # ... while a topic the '*' rule covers is granted
        finally:
            conn.close()

        conn, _, _ = self.connect('guest')
        try:
            self.assertEqual(self.subscribed(conn, 1, 'public/news'), 0)
        finally:
            conn.close()

    def test_denied_publish_reaches_nobody(self):
        """MQTT cannot refuse a PUBLISH, so a denied one is dropped while the
        acknowledgement still flows: the publisher is not left retransmitting,
        and the subscribers of that topic see nothing"""
        sub, _, _ = self.connect('sensor-1')
        try:
            self.assertEqual(self.subscribed(sub, 1, 'sensors/secret'), 0)

            guest, _, _ = self.connect('guest')
            try:
                guest.sendall(sol_test.create_publish('sensors/secret',
                                                      b'stolen', qos=1, mid=9))
                self.assertEqual(sol_test.read_ack(guest.recv(100))[0], 0x40)
            finally:
                guest.close()

            self.assert_nothing_arrives(sub)
        finally:
            sub.close()

    def test_user_rule_matches_the_username(self):
        """A rule can name the username the client presented instead of its
        client id: alice may read the sensors tree, but not write it"""
        with open(LOG_PATH, 'a'):
            pass

        reader, _, _ = self.connect('alice-laptop', username='alice')
        try:
            self.assertEqual(self.subscribed(reader, 1, 'sensors/#'), 0)
        finally:
            reader.close()

        # The same user may not publish: the rule only grants reads
        sub, _, _ = self.connect('sensor-1')
        try:
            self.assertEqual(self.subscribed(sub, 1, 'sensors/#'), 0)
            writer, _, _ = self.connect('alice-laptop', username='alice')
            try:
                writer.sendall(sol_test.create_publish('sensors/temperature',
                                                       b'fake', qos=1, mid=3))
                self.assertEqual(sol_test.read_ack(writer.recv(100))[0], 0x40)
            finally:
                writer.close()
            self.assert_nothing_arrives(sub)
        finally:
            sub.close()

    def test_will_needs_write_permission(self):
        """The will is a publication the broker makes on the client's behalf,
        so a client that may not write a topic cannot write it through its
        will either: the CONNECT is refused with Not authorized"""
        conn = socket.create_connection((HOST, PORT), timeout=5)
        conn.settimeout(3)
        try:
            conn.sendall(sol_test.create_connect('guest',
                                                 will_topic='sensors/secret',
                                                 will_payload=b'boom'))
            packet = conn.recv(100)
            connack, rc = sol_test.read_connack(packet)
            self.assertEqual(connack, 32)
            self.assertEqual(rc, 5)  # MQTT_NOT_AUTHORIZED
            self.assertEqual(conn.recv(100), b'')  # flushed then closed
        finally:
            conn.close()


if __name__ == '__main__':
    unittest.main()
