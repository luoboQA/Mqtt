import os
import subprocess
import unittest

import sol_test

CONF_PATH = '/tmp/sol_cli_test.conf'

VALID = """# Generated by tests/integration/test_cli.py
log_level WARNING
ip_port 18891
max_memory 16MB
keepalive 60s
"""


class TestCli(unittest.TestCase):
    """The command line surface used by service managers and by the person
    deploying the broker: version, help and a configuration check that fails
    on anything the parser would otherwise ignore"""

    def setUp(self):
        with open(CONF_PATH, 'w') as fh:
            fh.write(VALID)

    def tearDown(self):
        if os.path.exists(CONF_PATH):
            os.remove(CONF_PATH)

    def run_sol(self, *args):
        return subprocess.run([sol_test.broker_bin(), *args],
                              capture_output=True, text=True, timeout=5)

    def test_version_and_help(self):
        version = self.run_sol('--version')
        self.assertEqual(version.returncode, 0)
        self.assertIn('Sol v', version.stdout)
        self.assertIn('MQTT broker 3.1.1', version.stdout)

        short = self.run_sol('-V')
        self.assertEqual(short.returncode, 0)
        self.assertEqual(short.stdout, version.stdout)

        help_out = self.run_sol('--help')
        self.assertEqual(help_out.returncode, 0)
        self.assertIn('Check the configuration', help_out.stdout)

    def test_check_config_accepts_a_valid_file(self):
        result = self.run_sol('--check-config', '-c', CONF_PATH)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('Configuration OK', result.stdout)

    def test_check_config_rejects_an_unknown_key(self):
        with open(CONF_PATH, 'a') as fh:
            fh.write('typo_key 1\n')
        result = self.run_sol('-t', '-c', CONF_PATH)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('unknown configuration key', result.stdout)

    def test_check_config_rejects_a_bad_value(self):
        with open(CONF_PATH, 'a') as fh:
            fh.write('ip_port 99999\n')
        result = self.run_sol('-t', '-c', CONF_PATH)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('not a TCP port', result.stdout)

    def test_explicit_missing_config_is_fatal(self):
        result = self.run_sol('-t', '-c', '/tmp/sol_does_not_exist.conf')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('Invalid configuration file', result.stderr)

    def test_unknown_option_is_rejected(self):
        result = self.run_sol('--no-such-option')
        self.assertNotEqual(result.returncode, 0)


if __name__ == '__main__':
    unittest.main()
