#!/bin/bash
#
# Run the integration suite against a ThreadSanitizer build.
#
# Two details make this different from a plain `python3
# tests/integration/run.py`:
#
# - ThreadSanitizer refuses to start on kernels randomizing the address space
#   with more than 28 bits ("FATAL: ThreadSanitizer: unexpected memory
#   mapping"), which is the default on recent ones. `setarch -R` runs the
#   broker with ASLR disabled for that process only.
# - The tests spawn the broker themselves as ./sol, so ./sol is temporarily
#   replaced by a wrapper doing exactly that, and the real binary is kept
#   aside as ./sol.tsan. Restore the normal binary when done (git checkout,
#   or copy it back from build-linux/).
#
# Reports land in /tmp/sol-tsan.log (and on the terminal).

set -e
cd "$(dirname "$0")/../.."

cmake -S . -B build-tsan -DTSAN=ON >/dev/null
make -C build-tsan sol
cp build-tsan/sol ./sol.tsan

cat > ./sol <<'WRAPPER'
#!/bin/bash
# Generated by tests/tools/run_tsan.sh: run the ThreadSanitizer binary with ASLR
# disabled, see that script for why
exec setarch "$(uname -m)" -R "$(dirname "$0")/sol.tsan" "$@" \
    2> >(tee -a "${TSAN_LOG:-/tmp/sol-tsan.log}" >&2)
WRAPPER
chmod +x ./sol

rm -f /tmp/sol-tsan.log
export TSAN_OPTIONS="${TSAN_OPTIONS:-halt_on_error=0}"
python3 -u tests/integration/run.py

echo
echo "ThreadSanitizer warnings: $(grep -c 'WARNING: ThreadSanitizer' /tmp/sol-tsan.log || true)"
echo "Full report: /tmp/sol-tsan.log"
